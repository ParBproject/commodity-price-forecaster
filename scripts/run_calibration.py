"""Regenerate results/calibration.json and the README calibration table from the snapshot.

    python scripts/run_calibration.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.benchmark import ARIMA_ORDER, DEFAULT_ORIGINS, load_snapshot  # noqa: E402
from src.calibration import LEVELS, calibrate_snapshot  # noqa: E402

OUT = ROOT / "results" / "calibration.json"
README = ROOT / "README.md"
START = "<!-- calibration:start (generated by scripts/run_calibration.py) -->"
END = "<!-- calibration:end -->"


def _r(x):
    return round(float(x), 6)


def build() -> dict:
    meta = json.loads((ROOT / "data" / "snapshot.json").read_text())
    snapshot = load_snapshot(ROOT / "data" / meta["file"])
    per = calibrate_snapshot(snapshot, meta["tickers"], DEFAULT_ORIGINS)
    per = {t: {k: ({kk: _r(vv) if isinstance(vv, float) else vv for kk, vv in v.items()}
                   if isinstance(v, dict) else v) for k, v in d.items()} for t, d in per.items()}
    pooled = {}
    for level in LEVELS:
        key = f"{int(round(level * 100))}%"
        hits = sum(d[key]["hits"] for d in per.values())
        n = sum(d[key]["n"] for d in per.values())
        from scipy.stats import binomtest

        pooled[key] = {"n": n, "hits": hits, "coverage": _r(hits / n),
                       "binom_p_value": _r(binomtest(hits, n, level).pvalue)}
    return {
        "schema_version": 1,
        "generated_by": "scripts/run_calibration.py",
        "snapshot_file": f"data/{meta['file']}",
        "method": "one-step ARIMA%s prediction intervals, rolling origin, refit every week" % (tuple(ARIMA_ORDER),),
        "n_origins": DEFAULT_ORIGINS,
        "per_commodity": per,
        "pooled": pooled,
    }


def markdown(res: dict) -> str:
    rows = ["| Commodity | 80% coverage | 95% coverage | 95% misses (below / above) | 95% binomial p |",
            "|---|---:|---:|---:|---:|"]
    for t, d in res["per_commodity"].items():
        a, b = d["80%"], d["95%"]
        rows.append(f"| {d['name']} (`{t}`) | {a['coverage'] * 100:.1f}% ({a['hits']}/{a['n']}) | "
                    f"{b['coverage'] * 100:.1f}% ({b['hits']}/{b['n']}) | "
                    f"{b['misses_below']} / {b['misses_above']} | {b['binom_p_value']:.3f} |")
    p80, p95 = res["pooled"]["80%"], res["pooled"]["95%"]
    rows.append(f"| **Pooled** | **{p80['coverage'] * 100:.1f}%** ({p80['hits']}/{p80['n']}) | "
                f"**{p95['coverage'] * 100:.1f}%** ({p95['hits']}/{p95['n']}) | | {p95['binom_p_value']:.3f} |")
    return "\n".join(rows)


def main() -> None:
    res = build()
    OUT.write_text(json.dumps(res, indent=2) + "\n")
    text = README.read_text()
    if START in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        README.write_text(head + START + "\n" + markdown(res) + "\n" + END + tail)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
