"""Score ARIMA(1,1,1) with and without the USDA yield feature on corn, wheat, soybeans.

    python scripts/run_usda_variant.py   # offline: reads the committed snapshots

Writes results/usda_variant.json and the README "USDA" block.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.benchmark import DEFAULT_ORIGINS, load_snapshot  # noqa: E402
from src.usda_loader import AG_TICKERS, load_cache  # noqa: E402
from src.usda_variant import BASE, VARIANT, evaluate_usda_variant  # noqa: E402

OUT = ROOT / "results" / "usda_variant.json"
START = "<!-- usda:start (generated by scripts/run_usda_variant.py) -->"
END = "<!-- usda:end -->"


def build() -> dict:
    meta = json.loads((ROOT / "data" / "snapshot.json").read_text())
    prices = load_snapshot(ROOT / "data" / meta["file"])
    cache = load_cache()
    per = {}
    for t in AG_TICKERS:
        _, scores = evaluate_usda_variant(prices[t], cache["records"][t])
        per[t] = {m: {k: (None if v is None else round(float(v), 6)) for k, v in s.items()}
                  for m, s in scores.items()}
    avg = {m: round(sum(per[t][m]["MASE"] for t in per) / len(per), 6) for m in (BASE, VARIANT)}
    return {
        "generated_by": "scripts/run_usda_variant.py",
        "usda_snapshot": "data/usda_cache.json",
        "usda_downloaded_on": cache["downloaded_on"],
        "price_snapshot": f"data/{meta['file']}",
        "n_origins": DEFAULT_ORIGINS,
        "feature": "log(latest NASS national yield estimate / previous crop year final), "
                   "as known at each week-end (reports dated the 12th), forward-filled",
        "commodities": {t: meta["tickers"][t] for t in AG_TICKERS},
        "per_commodity": per,
        "average_mase": avg,
        "mase_change": round(avg[VARIANT] - avg[BASE], 6),
    }


def markdown(r: dict) -> str:
    lines = [START, "",
             f"Same 52 weekly one-step origins as the leaderboard, grains only. USDA data: "
             f"NASS Quick Stats national yield forecasts and finals, snapshot "
             f"`{r['usda_snapshot']}` pulled {r['usda_downloaded_on']}.", "",
             f"| Commodity | {BASE} MASE | {VARIANT} MASE | Change |", "|---|---:|---:|---:|"]
    for t, s in r["per_commodity"].items():
        b, v = s[BASE]["MASE"], s[VARIANT]["MASE"]
        lines.append(f"| {r['commodities'][t]} (`{t}`) | {b:.3f} | {v:.3f} | {v - b:+.3f} |")
    a = r["average_mase"]
    lines += [f"| **Average** | **{a[BASE]:.3f}** | **{a[VARIANT]:.3f}** | "
              f"**{r['mase_change']:+.3f}** |", "", END]
    return "\n".join(lines)


def main() -> None:
    r = build()
    OUT.write_text(json.dumps(r, indent=1) + "\n")
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START in text:
        s, e = text.index(START), text.index(END) + len(END)
        text = text[:s] + markdown(r) + text[e:]
    readme.write_text(text)
    print(json.dumps(r["average_mase"]), r["mase_change"])
    print(markdown(r))


if __name__ == "__main__":
    main()
